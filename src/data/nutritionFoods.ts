export type FoodCategory =
  | 'proteins'
  | 'carbohydrates'
  | 'vegetables'
  | 'fruits'
  | 'healthy_fats'
  | 'dairy_alternatives';

export interface FoodItem {
  id: string;
  name: string;
  category: FoodCategory;
  /** Calories per 100g */
  calories: number;
  /** Protein in grams per 100g */
  protein: number;
  /** Carbohydrates in grams per 100g */
  carbohydrates: number;
  /** Fats in grams per 100g */
  fat: number;
  /** Standard suggested serving in grams (e.g., 100g, 150g, 30g) */
  defaultServingGrams: number;
  /** Unit description for clarity */
  servingUnitName?: string;
  /** Brief tip or highlight for muscle building / fat loss */
  highlight?: string;
  /** Image URL for visual catalog */
  imageUrl?: string;
}

export function getFoodImageUrl(food: FoodItem | string): string {
  if (typeof food === 'string') {
    return `/foods/${food}.webp`;
  }
  return food.imageUrl || `/foods/${food.id}.webp`;
}

